-- DysLearn schema (PostgreSQL / Supabase), adapted from proposal 001.docx §5.5.1
-- data dictionary. Tables beyond the proposal's dictionary (the content bank,
-- per-student adaptive difficulty state, parent accounts, the book library and the
-- parent guidelines feed) are pragmatic additions to support the client's requested UI.
--
-- Idempotent: `npm run db:migrate` runs this whole file and is safe to re-run.

CREATE TABLE IF NOT EXISTS teachers (
  teacher_id     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  firstname      TEXT NOT NULL,
  lastname       TEXT NOT NULL,
  email          TEXT UNIQUE NOT NULL,
  mobile         TEXT,
  subject        TEXT,
  userpassword   TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS students (
  student_id     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  regno          TEXT UNIQUE NOT NULL,
  firstname      TEXT NOT NULL,
  middlename     TEXT,
  lastname       TEXT NOT NULL,
  grade          INTEGER NOT NULL,
  email          TEXT,
  username       TEXT UNIQUE NOT NULL,
  userpassword   TEXT NOT NULL,
  parent_mobile  TEXT,
  teacher_id     INTEGER REFERENCES teachers(teacher_id),
  attendance_days INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS parents (
  parent_id      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  firstname      TEXT NOT NULL,
  lastname       TEXT NOT NULL,
  email          TEXT UNIQUE NOT NULL,
  mobile         TEXT,
  userpassword   TEXT NOT NULL
);

-- Which children a parent account can see. Populated when a parent registers with
-- a valid pupil registration number, or by a teacher linking them.
CREATE TABLE IF NOT EXISTS parent_children (
  parent_id      INTEGER NOT NULL REFERENCES parents(parent_id) ON DELETE CASCADE,
  student_id     INTEGER NOT NULL REFERENCES students(student_id) ON DELETE CASCADE,
  PRIMARY KEY (parent_id, student_id)
);

CREATE TABLE IF NOT EXISTS subjects (
  subject_id     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  subject_name   TEXT UNIQUE NOT NULL,
  subject_desc   TEXT
);

-- Content bank (pragmatic addition beyond the proposal's dictionary)
CREATE TABLE IF NOT EXISTS exercises (
  exercise_id    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  subject_id     INTEGER NOT NULL REFERENCES subjects(subject_id),
  type           TEXT NOT NULL CHECK (type IN ('dragdrop','scramble','dictation','addition','subtraction','multiplication','division')),
  difficulty     INTEGER NOT NULL CHECK (difficulty BETWEEN 1 AND 5),
  content_json   JSONB NOT NULL
);
CREATE INDEX IF NOT EXISTS exercises_lookup_idx ON exercises (subject_id, type, difficulty);

-- Per-student, per-subject adaptive difficulty state (pragmatic addition)
CREATE TABLE IF NOT EXISTS student_difficulty (
  student_id     INTEGER NOT NULL REFERENCES students(student_id) ON DELETE CASCADE,
  subject_id     INTEGER NOT NULL REFERENCES subjects(subject_id),
  level          INTEGER NOT NULL DEFAULT 1 CHECK (level BETWEEN 1 AND 5),
  PRIMARY KEY (student_id, subject_id)
);

-- Digital book / storybook library shown on the pupil "Books" page and managed
-- from the teacher portal. `pdf_path` is the object path in the Supabase Storage
-- "books" bucket.
CREATE TABLE IF NOT EXISTS books (
  book_id        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  subject_id     INTEGER NOT NULL REFERENCES subjects(subject_id),
  grade          INTEGER NOT NULL,
  title          TEXT NOT NULL,
  book_type      TEXT NOT NULL DEFAULT 'textbook' CHECK (book_type IN ('textbook','storybook','workbook')),
  pdf_path       TEXT,
  uploaded_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- A pupil's learning session (a run of exercise attempts), not a login session.
CREATE TABLE IF NOT EXISTS sessions (
  session_id     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  student_id     INTEGER NOT NULL REFERENCES students(student_id) ON DELETE CASCADE,
  starttime      TIMESTAMPTZ NOT NULL DEFAULT now(),
  endtime        TIMESTAMPTZ
);

CREATE TABLE IF NOT EXISTS activity_attempts (
  attempt_id     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  session_id     INTEGER NOT NULL REFERENCES sessions(session_id) ON DELETE CASCADE,
  exercise_id    INTEGER NOT NULL REFERENCES exercises(exercise_id),
  student_id     INTEGER NOT NULL REFERENCES students(student_id) ON DELETE CASCADE,
  latency_ms     INTEGER NOT NULL,
  score          DOUBLE PRECISION NOT NULL,
  grade          TEXT NOT NULL,
  created_at     TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS activity_attempts_student_idx ON activity_attempts (student_id, created_at DESC);

CREATE TABLE IF NOT EXISTS speechlogs (
  log_id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  student_id     INTEGER NOT NULL REFERENCES students(student_id) ON DELETE CASCADE,
  input_text     TEXT,
  output_text    TEXT,
  timestamp      TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS progress_reports (
  report_id      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  student_id     INTEGER NOT NULL REFERENCES students(student_id) ON DELETE CASCADE,
  average_score  DOUBLE PRECISION NOT NULL,
  strengths      TEXT,
  challenges     TEXT,
  generated_at   TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- The "Learning Insights & Recommendations" feed the parent portal shows: an
-- auto-generated AI insight plus a free-text note the teacher writes to the parent.
CREATE TABLE IF NOT EXISTS guidelines (
  guideline_id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  student_id     INTEGER NOT NULL REFERENCES students(student_id) ON DELETE CASCADE,
  ai_insight     TEXT,
  teacher_note   TEXT,
  created_at     TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Login sessions for express-session (connect-pg-simple's expected shape). Kept in
-- the database because serverless hosts (Vercel) don't share memory between requests.
CREATE TABLE IF NOT EXISTS user_sessions (
  sid            VARCHAR NOT NULL PRIMARY KEY,
  sess           JSON NOT NULL,
  expire         TIMESTAMP(6) NOT NULL
);
CREATE INDEX IF NOT EXISTS user_sessions_expire_idx ON user_sessions (expire);

-- Supabase exposes the `public` schema through its auto-generated REST API. The app
-- talks to Postgres directly as the owner role (which bypasses RLS), so enabling RLS
-- with no policies keeps every table — pupils' data included — closed to that API.
ALTER TABLE teachers           ENABLE ROW LEVEL SECURITY;
ALTER TABLE students           ENABLE ROW LEVEL SECURITY;
ALTER TABLE parents            ENABLE ROW LEVEL SECURITY;
ALTER TABLE parent_children    ENABLE ROW LEVEL SECURITY;
ALTER TABLE subjects           ENABLE ROW LEVEL SECURITY;
ALTER TABLE exercises          ENABLE ROW LEVEL SECURITY;
ALTER TABLE student_difficulty ENABLE ROW LEVEL SECURITY;
ALTER TABLE books              ENABLE ROW LEVEL SECURITY;
ALTER TABLE sessions           ENABLE ROW LEVEL SECURITY;
ALTER TABLE activity_attempts  ENABLE ROW LEVEL SECURITY;
ALTER TABLE speechlogs         ENABLE ROW LEVEL SECURITY;
ALTER TABLE progress_reports   ENABLE ROW LEVEL SECURITY;
ALTER TABLE guidelines         ENABLE ROW LEVEL SECURITY;
ALTER TABLE user_sessions      ENABLE ROW LEVEL SECURITY;
